function normalizeSearchText(text: string): string {
  return text
    .toLowerCase()
    .replace(/[.,\-\/()]/g, ' ')
    .replace(/\b(st|str)\b/g, 'street')
    .replace(/\b(rd)\b/g, 'road')
    .replace(/\b(ave|av)\b/g, 'avenue')
    .replace(/\b(blvd|bvd)\b/g, 'boulevard')
    .replace(/\b(hwy)\b/g, 'highway')
    .replace(/\b(brgy|bgy)\b/g, 'barangay')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Smart fuzzy search function for landmarks across the Philippines.
 * Matches name, displayName, aliases, city, and barangay with street abbreviation support.
 */
export function searchPhilippineLandmarks(query: string, limit = 8): PhilippineLandmark[] {
  const rawQ = query.trim().toLowerCase();
  if (!rawQ) {
    return PHILIPPINE_LANDMARKS.filter((l) => l.isPopular).slice(0, limit);
  }

  const normQ = normalizeSearchText(rawQ);
  const scoreMap = new Map<PhilippineLandmark, number>();

  for (const item of PHILIPPINE_LANDMARKS) {
    let score = 0;
    const normName = normalizeSearchText(item.name);
    const normDisplay = normalizeSearchText(item.displayName);
    const normCity = normalizeSearchText(item.city);
    const normBarangay = normalizeSearchText(item.barangay);
    const normAliases = (item.aliases || []).map((a) => normalizeSearchText(a));

    // Exact or prefix matches on normalized name get highest priority
    if (normName === normQ) {
      score += 150;
    } else if (normName.startsWith(normQ)) {
      score += 110;
    } else if (normName.includes(normQ)) {
      score += 60;
    }

    // Direct match on alias (e.g. "plv", "moa", "ust", "pgh", "edsa", "nlex")
    if (normAliases.some((a) => a === normQ)) {
      score += 100;
    } else if (normAliases.some((a) => a.startsWith(normQ))) {
      score += 75;
    } else if (normAliases.some((a) => a.includes(normQ))) {
      score += 45;
    }

    if (normCity.startsWith(normQ)) score += 30;
    if (normDisplay.includes(normQ)) score += 20;
    if (normBarangay.includes(normQ)) score += 15;

    // Check multi-word query tokens
    const tokens = normQ.split(' ').filter(Boolean);
    if (tokens.length > 1) {
      const allMatch = tokens.every(
        (t) =>
          normName.includes(t) ||
          normDisplay.includes(t) ||
          normCity.includes(t) ||
          normAliases.some((a) => a.includes(t))
      );
      if (allMatch) score += 40;
    }

    if (score > 0) {
      scoreMap.set(item, score);
    }
  }

  return Array.from(scoreMap.entries())
    .sort((a, b) => b[1] - a[1])
    .map(([item]) => item)
    .slice(0, limit);
}
