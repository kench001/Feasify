// Helper function to translate any text string to Filipino with deep pattern and phrase matching
export function translateToFilipino(text: string): string {
  if (!text) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  const lower = trimmed.toLowerCase();

  // 1. Direct dictionary match
  if (phraseDictionary[lower]) {
    return applyMatch(text, trimmed, phraseDictionary[lower]);
  }

  // 2. Leading prefix strip and re-attach (e.g., "+ Add Contributor", "#1 Investor / Partner", "› Dashboard")
  const prefixMatch = trimmed.match(/^([+\-#›•|]\s*|\#\d+\s+|\d+\.\s+)(.+)$/);
  if (prefixMatch) {
    const prefix = prefixMatch[1];
    const rest = prefixMatch[2].trim().toLowerCase();
    if (phraseDictionary[rest]) {
      return applyMatch(text, trimmed, prefix + phraseDictionary[rest]);
    }
  }

  // 3. Trailing arrow/icon strip and re-attach (e.g., "Manage Proposals ->", "Manage Proposals →")
  const arrowMatch = trimmed.match(/^(.*?)\s*([→\-><]+|\&rarr\;)$/);
  if (arrowMatch) {
    const baseWord = arrowMatch[1].trim().toLowerCase();
    const arrow = arrowMatch[2];
    if (phraseDictionary[baseWord]) {
      return applyMatch(text, trimmed, `${phraseDictionary[baseWord]} ${arrow}`);
    }
  }

  // 4. Trailing punctuation check (e.g., ":", "...", ".", "?", "!")
  const punctMatch = trimmed.match(/^(.*?)([:.!?]+)$/);
  if (punctMatch) {
    const baseWord = punctMatch[1].trim().toLowerCase();
    const punct = punctMatch[2];
    if (phraseDictionary[baseWord]) {
      return applyMatch(text, trimmed, phraseDictionary[baseWord] + punct);
    }
  }

  // 5. Parenthesized count suffix check (e.g., "Active Proposals (4)", "Total Capital (Proposal)")
  const parenMatch = trimmed.match(/^(.*?)\s*(\(.*?\))$/);
  if (parenMatch) {
    const baseWord = parenMatch[1].trim().toLowerCase();
    const paren = parenMatch[2];
    if (phraseDictionary[baseWord]) {
      return applyMatch(text, trimmed, `${phraseDictionary[baseWord]} ${paren}`);
    }
  }

  // 6. Dynamic Month & Draft patterns
  // "Month 1", "Month 2", etc.
  const monthMatch = trimmed.match(/^Month\s+(\d+)$/i);
  if (monthMatch) {
    return applyMatch(text, trimmed, `Buwan ${monthMatch[1]}`);
  }

  // "Lock & Proceed to Month 2" or "Lock & Proceed to Month"
  const lockMonthMatch = trimmed.match(/^Lock\s+&\s+Proceed\s+to\s+Month\s*(\d*)$/i);
  if (lockMonthMatch) {
    const num = lockMonthMatch[1] ? ` ${lockMonthMatch[1]}` : "";
    return applyMatch(text, trimmed, `I-lock at Magpatuloy sa Buwan${num}`);
  }

  // "Month 1 Drafts:" or "MONTH 1 DRAFTS:"
  const monthDraftsMatch = trimmed.match(/^Month\s+(\d+)\s+Drafts:?$/i);
  if (monthDraftsMatch) {
    return applyMatch(text, trimmed, `Mga Draft sa Buwan ${monthDraftsMatch[1]}:`);
  }

  // "Draft 1 (Primary)"
  const draftPrimaryMatch = trimmed.match(/^Draft\s+(\d+)\s*\(Primary\)$/i);
  if (draftPrimaryMatch) {
    return applyMatch(text, trimmed, `Draft ${draftPrimaryMatch[1]} (Pangunahin)`);
  }

  // "1 Listed", "0 Listed"
  const listedMatch = trimmed.match(/^(\d+)\s+Listed$/i);
  if (listedMatch) {
    return applyMatch(text, trimmed, `${listedMatch[1]} Nakalista`);
  }

  // "Approved Business Charter • Created: 04/10/2026" or "Approved Business Charter • Created: Recent"
  const charterCreatedMatch = trimmed.match(/^Approved\s+Business\s+Charter\s*•\s*Created:\s*(.*)$/i);
  if (charterCreatedMatch) {
    const val = charterCreatedMatch[1].trim();
    const transVal = val.toLowerCase() === "recent" ? "Kamakailan" : val;
    return applyMatch(text, trimmed, `Naaprubahang Business Charter • Ginawa: ${transVal}`);
  }

  // "Total: ₱150,000.00 (100% Balanced with Proposal Requirement)"
  const totalBalanceMatch = trimmed.match(/^Total:\s*(₱[\d,.]+)\s*\((.*?)\)$/i);
  if (totalBalanceMatch) {
    const amt = totalBalanceMatch[1];
    const parenContent = totalBalanceMatch[2];
    const transParen = parenContent.includes("Balanced") ? "100% Balanse sa Kinakailangan ng Proposal" : parenContent;
    return applyMatch(text, trimmed, `Kabuuan: ${amt} (${transParen})`);
  }

  // "2 Partners participating in initial venture capitalization."
  const partnersCapMatch = trimmed.match(/^(\d+)\s+Partners?\s+participating\s+in\s+initial\s+venture\s+capitalization\.?$/i);
  if (partnersCapMatch) {
    return applyMatch(text, trimmed, `${partnersCapMatch[1]} Kasosyo na kalahok sa unang capitalization ng negosyo.`);
  }

  // "SURROUNDING ESTABLISHMENTS FROM MAP (QUEZON CITY):"
  const surrMapMatch = trimmed.match(/^SURROUNDING\s+ESTABLISHMENTS\s+FROM\s+MAP\s*\((.*?)\):?$/i);
  if (surrMapMatch) {
    return applyMatch(text, trimmed, `MGA KALAPIT NA ESTABLISIMYENTO MULA SA MAPA (${surrMapMatch[1]}):`);
  }

  // "DIRECT RIVALS FROM MAP (QUEZON CITY):"
  const directRivalsMatch = trimmed.match(/^DIRECT\s+RIVALS\s+FROM\s+MAP\s*\((.*?)\):?$/i);
  if (directRivalsMatch) {
    return applyMatch(text, trimmed, `MGA DIREKTANG KARIBAL MULA SA MAPA (${directRivalsMatch[1]}):`);
  }

  // "GPS PROXIMITY (<=3KM)"
  const gpsMatch = trimmed.match(/^GPS\s+PROXIMITY\s*\((.*?)\)$/i);
  if (gpsMatch) {
    return applyMatch(text, trimmed, `LAPIT SA GPS (${gpsMatch[1]})`);
  }

  // "Showing X of Y results"
  const showingMatch = trimmed.match(/^Showing\s+(\d+)\s+to\s+(\d+)\s+of\s+(\d+)\s+results$/i);
  if (showingMatch) {
    return applyMatch(
      text,
      trimmed,
      `Nagpapakita ng ${showingMatch[1]} hanggang ${showingMatch[2]} sa ${showingMatch[3]} mga resulta`
    );
  }

  // "Page X of Y"
  const pageMatch = trimmed.match(/^Page\s+(\d+)\s+of\s+(\d+)$/i);
  if (pageMatch) {
    return applyMatch(text, trimmed, `Pahina ${pageMatch[1]} ng ${pageMatch[2]}`);
  }

  // 7. Partial phrase replacements for multi-part text nodes (e.g. "Direct CapEx Equipment: ", "Monthly Fixed OpEx: ")
  let processed = trimmed;
  let hasReplacement = false;
  const multiReplacements: [RegExp, string][] = [
    [/Total CapEx Equipment:?/gi, "Kabuuang Kagamitan (CapEx):"],
    [/Monthly Fixed OpEx:?/gi, "Buwanang Fixed OpEx:"],
    [/Initial Capital Contributed/gi, "Unang Puhunang Inambag"],
    [/INITIAL CAPITAL CONTRIBUTED/gi, "UNANG PUHUNANG INAMBAG"],
    [/Total Capital \(Proposal\)/gi, "Kabuuang Puhunan (Proposal)"],
    [/TOTAL CAPITAL \(PROPOSAL\)/gi, "KABUUANG PUHUNAN (PROPOSAL)"],
    [/TOTAL CAPITAL OVERVIEW/gi, "KABUUANG TANAW SA PUHUNAN"],
    [/Business Feasibility Capital Summary/gi, "Buod ng Puhunan sa Feasibility ng Negosyo"],
    [/Approved Business Charter/gi, "Naaprubahang Business Charter"],
    [/Est\. Monthly Revenue/gi, "Tinatayang Buwanang Kita"],
    [/EST\. MONTHLY REVENUE/gi, "TINATAYANG BUWANANG KITA"],
    [/TOTAL APPROVED/gi, "KABUUANG NAAPRUBAHAN"],
    [/FEASIBILITY STATUS/gi, "KATAYUAN NG FEASIBILITY"],
    [/IN PROGRESS/gi, "KASALUKUYANG GINAGAWA"],
    [/AVG\. ESTIMATED ROI/gi, "KATAMTAMANG TINATAYANG ROI"],
    [/MARKET ENVIRONMENT & DEMOGRAPHICS/gi, "KAPALIGIRAN NG MERKADO AT DEMOGRAPIYA"],
    [/Market & Competitive Indicators/gi, "Mga Indikasyon sa Merkado at Kompetisyon"],
    [/DIRECT COMPETITORS/gi, "MGA DIREKTANG KAKUMPITENSYA"],
    [/NEARBY ESTABLISHMENTS AFFECTING BUSINESS ROI/gi, "MGA KALAPIT NA ESTABLISIMYENTO NA NAKAKAAPEKTO SA ROI NG NEGOSYO"],
    [/Lock & Proceed to Month/gi, "I-lock at Magpatuloy sa Buwan"],
  ];

  for (const [pattern, repl] of multiReplacements) {
    if (pattern.test(processed)) {
      processed = processed.replace(pattern, repl);
      hasReplacement = true;
    }
  }

  if (hasReplacement) {
    return applyMatch(text, trimmed, processed);
  }

  return text;
}

function applyMatch(originalFullText: string, trimmed: string, translated: string): string {
  // Preserve ALL CAPS if the entire source was uppercase
  if (trimmed === trimmed.toUpperCase() && trimmed.length > 1 && !/[a-z]/.test(trimmed)) {
    return originalFullText.replace(trimmed, translated.toUpperCase());
  }
  // Preserve Capitalized first letter
  if (trimmed[0] === trimmed[0].toUpperCase() && translated[0]) {
    const capitalized = translated.charAt(0).toUpperCase() + translated.slice(1);
    return originalFullText.replace(trimmed, capitalized);
  }
  return originalFullText.replace(trimmed, translated);
}
